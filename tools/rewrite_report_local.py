def rewrite_docx() -> None:
    if not BACKUP.exists():
        shutil.copy2(SRC, BACKUP)
    shutil.copy2(SRC, OUT)

    with zipfile.ZipFile(OUT, "r") as zin:
        files = {name: zin.read(name) for name in zin.namelist()}

    root = ET.fromstring(files["word/document.xml"])
    changed: list[str] = []
    for paragraph in root.findall(".//w:body/w:p", NS):
        texts = paragraph.findall(".//w:t", NS)
        if not texts:
            continue
        current = "".join(text.text or "" for text in texts).strip()
        replacement = REPLACEMENTS.get(current)
        if replacement is None:
            continue
        texts[0].text = replacement
        for text in texts[1:]:
            text.text = ""
        changed.append(current)

    files["word/document.xml"] = ET.tostring(
        root,
        encoding="utf-8",
        xml_declaration=True,
    )
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as zout:
        for name, data in files.items():
            zout.writestr(name, data)

    missing = [key for key in REPLACEMENTS if key not in changed]
    print(f"changed={len(changed)}")
    print(f"missing={len(missing)}")
    for item in missing:
        print(f"MISS: {item[:100]}")


if __name__ == "__main__":
    rewrite_docx()
